#!/usr/bin/env node
/**
 * scripts/scan-example-secrets.js
 *
 * Scans example/template env files for values that look like real secret
 * material: Stellar StrKey-formatted secrets, BIP-39 mnemonics, or realistic
 * hex secrets that should never appear in committed template files.
 *
 * Run manually:  node scripts/scan-example-secrets.js
 * Run in CI:     (added as a dedicated job in .github/workflows/ci.yml)
 *
 * Exit code 0 → clean. Exit code 1 → one or more violations found.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const glob = require('fs');

// ── Files to scan ────────────────────────────────────────────────────────────
// Explicit list so we can scan both root and sub-package example files without
// accidentally pulling in node_modules, .git, or third-party fixtures.
const SCAN_TARGETS = [
  '.env.example',
  'backend/.env.example',
  'frontend/.env.example',
  'frontend/.env.local.example',
];

// ── Detection patterns ───────────────────────────────────────────────────────

/**
 * Stellar secret key (StrKey, S-prefix, 56 Base32 chars).
 * A real secret key starts with S and encodes exactly 32 bytes in Stellar's
 * modified Base32 alphabet (A-Z, 2-7).
 *
 * We match it as a standalone value (not embedded inside a longer word) to
 * avoid false-positives on comments or URLs.
 */
const STELLAR_SECRET_KEY = /(?<![A-Z2-7])S[A-Z2-7]{55}(?![A-Z2-7])/;

/**
 * BIP-39 mnemonic phrase (12 or 24 lowercase English words separated by spaces).
 * The BIP-39 wordlist contains ~2048 words; we use a lightweight heuristic:
 * 12 or more consecutive lowercase dictionary words (3–8 chars each) separated
 * by single spaces. This catches the pattern committed in this repo's history
 * while avoiding false-positives on prose comments.
 */
const BIP39_MNEMONIC = /\b([a-z]{3,8} ){11,23}[a-z]{3,8}\b/;

/**
 * Realistic hex secret — a 32-byte (64 hex char) or 64-byte (128 hex char)
 * value that looks like it was generated by `openssl rand -hex 32`.
 * We exclude obvious counter-examples: all-zeros (0{64}), sequential runs
 * (0123456789ab...), and values that are clearly labeled as REPLACE_ME or
 * similar.
 *
 * We only flag values assigned directly in the file (VAR=<hex>), not hex
 * strings in comments or URLs.
 */
const HEX_SECRET_ASSIGNMENT = /^[A-Z_]+=([0-9a-f]{64}|[0-9a-f]{128})\b/;

/**
 * Patterns that are obviously fake and should be allowed through the hex check.
 * These match the full 64-char hex value on the right-hand side of the assignment.
 */
const OBVIOUSLY_FAKE_HEX = [
  /^0{64}$/,                          // all zeros
  /^(?:0123456789abcdef){4}$/,        // sequential (0123...abcdef repeated)
  /^(?:abcdef0123456789){4}$/,        // reverse sequential
  /^([\da-f])\1{63}$/,               // all same character
];

// ── Scanner ──────────────────────────────────────────────────────────────────

let violations = 0;

for (const relPath of SCAN_TARGETS) {
  const absPath = path.resolve(__dirname, '..', relPath);

  if (!fs.existsSync(absPath)) {
    // Not every package has every example file; skip silently.
    continue;
  }

  const lines = fs.readFileSync(absPath, 'utf8').split('\n');

  lines.forEach((line, idx) => {
    const lineNo = idx + 1;

    // Skip blank lines and pure comment lines.
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;

    // Extract the value side of KEY=value (strip inline comments).
    const eqIdx = line.indexOf('=');
    if (eqIdx === -1) return;
    const value = line.slice(eqIdx + 1).replace(/#.*$/, '').trim();

    // 1. Stellar secret key (S + 55 Base32 chars)
    if (STELLAR_SECRET_KEY.test(value)) {
      console.error(
        `\u274c  ${relPath}:${lineNo} — Stellar secret key (S-prefix StrKey) detected.\n` +
        `   Replace with a clearly-fake placeholder, e.g. REPLACE_ME_stellar_secret_key`
      );
      violations++;
    }

    // 2. BIP-39 mnemonic (12–24 lowercase words)
    if (BIP39_MNEMONIC.test(value)) {
      console.error(
        `\u274c  ${relPath}:${lineNo} — Value looks like a BIP-39 mnemonic phrase.\n` +
        `   Replace with a clearly-fake placeholder, e.g. REPLACE_ME_mnemonic`
      );
      violations++;
    }

    // 3. Realistic hex secret (64 or 128 chars) that isn't obviously fake
    const hexMatch = line.match(HEX_SECRET_ASSIGNMENT);
    if (hexMatch) {
      const hexValue = hexMatch[1];
      const isFake = OBVIOUSLY_FAKE_HEX.some((pat) => pat.test(hexValue));
      if (!isFake) {
        console.error(
          `\u274c  ${relPath}:${lineNo} — Realistic hex secret detected (${hexValue.length} chars).\n` +
          `   Replace with a clearly-fake placeholder, e.g. REPLACE_ME_run_openssl_rand_hex_32`
        );
        violations++;
      }
    }
  });
}

if (violations === 0) {
  console.log('\u2705  scan-example-secrets: no real-format secret material found in example files.');
  process.exit(0);
} else {
  console.error(
    `\n\u274c  scan-example-secrets: ${violations} violation(s) found.\n` +
    `   Example files must not contain real-format secret material.\n` +
    `   See docs/security.md for guidance on safe placeholder values.`
  );
  process.exit(1);
}
